/**
 * Get technology icon by name
 * Returns appropriate SVG icon for each technology
 *
 * @param {string} name - Technology name
 * @param {string} size - Icon size (default: 24)
 * @returns {string} SVG HTML string
 */
export function getTechIcon(name, size = '24') {
  const icons = {
    'Python': PythonIcon(size),
    'Java': JavaIcon(size),
    'JavaScript': JavaScriptIcon(size),
    'TypeScript': TypeScriptIcon(size),
    'C/C++': CppIcon(size),
    'Docker': DockerIcon(size),
    'Node.js': NodeIcon(size),
    'GitHub': GitHubIcon(size),
  };

  // Return specific icon if available, otherwise return generic code icon
  return icons[name] || CodeIcon(size);
}

